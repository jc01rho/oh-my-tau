#![allow(dead_code)]
//! `generate_image`: omp's image generation tool
//! (`pi-coding-agent/src/tools/image-gen.ts`).
//!
//! One request describes an image with structured fields (`subject`, `action`, `scene`,
//! `composition`, `lighting`, `style`, `text`, `changes`) which are assembled into a single
//! prompt, plus optional reference images for editing. Candidates come from the `image` model
//! role: an explicit `model` selector wins, otherwise the role's own selector, then the session
//! model (when it is itself an image-generation model), then `retry.fallbackChains.image`.
//!
//! Three transports cover the image-generation APIs the catalog names:
//!
//! * `openai-images` - `POST {base}/images/generations`, or `/images/edits` (multipart) when
//!   reference images are supplied.
//! * `openrouter-images` - `POST {base}/images/generations` with `input_references`.
//! * `google-generative-ai` - `POST {base}/models/{id}:generateContent` with `IMAGE` modality.
//!
//! Each candidate is tried in order; failures accumulate into one exhausted-chain error that
//! names the attempted models, the per-provider reasons (flattened, capped at
//! [`MAX_FAILURE_REASON_CHARS`]) and everything skipped (offline provider restriction,
//! unsupported api, missing credentials). Generated bytes are written to
//! `<tmpdir>/omp-image-<id>.<ext>` and the tool text lists the paths with their size/quality.
//!
//! Not ported here, and deliberately reported as skips instead of silent guesses: the
//! `openai-responses` / `openai-codex-responses` hosted carrier (the Rust `Model` has no
//! `hostedImage`/`imageModel` fields to resolve one), `google-gemini-cli` (Cloud Code Assist
//! credentials), and the resample path's `Bun.Image` (replaced by the `image` crate). The
//! tool description lives in `prompts/tools/image-gen.md` upstream and is not carried here.

use std::collections::HashSet;
use std::io::Cursor;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::{Duration, SystemTime, UNIX_EPOCH};

use anyhow::{anyhow, bail, Context as _, Result};
use base64::engine::general_purpose::STANDARD;
use base64::Engine as _;
use serde::{Deserialize, Serialize};
use serde_json::{json, Value};

use omp_providers::{AgentDir, ResolvedModel};

/// Whole-request budget (`IMAGE_TIMEOUT`): three minutes per candidate.
const IMAGE_TIMEOUT: Duration = Duration::from_secs(3 * 60);

/// Largest reference image accepted from disk or base64 (`MAX_IMAGE_SIZE`).
const MAX_IMAGE_SIZE: u64 = 35 * 1024 * 1024;

/// Per-failure character cap: a gateway HTML error page must not reach the model verbatim.
const MAX_FAILURE_REASON_CHARS: usize = 300;

/// `aspect_ratio` enum, in upstream order.
const ASPECT_RATIOS: [&str; 7] = ["1:1", "3:4", "4:3", "9:16", "16:9", "3:2", "2:3"];

/// `image_size` enum, in upstream order.
const IMAGE_SIZES: [&str; 3] = ["1024x1024", "1536x1024", "1024x1536"];

/// Aspect ratio to the nearest OpenAI `size` (providers treat it as a hint; the result is
/// resampled to an explicit `image_size` afterwards).
fn aspect_size(aspect_ratio: &str) -> Option<&'static str> {
    match aspect_ratio {
        "1:1" => Some("1024x1024"),
        "3:4" | "9:16" | "2:3" => Some("1024x1536"),
        "4:3" | "16:9" | "3:2" => Some("1536x1024"),
        _ => None,
    }
}

