fn label(model: &ResolvedModel) -> String {
    format!("{}/{}", model.provider, model.id)
}

async fn post_json(request: reqwest::RequestBuilder, name: &str) -> Result<Value> {
    let response = request
        .send()
        .await
        .map_err(|e| anyhow!("{name} request failed: {e}"))?;
    let status = response.status();
    let text = response.text().await.unwrap_or_default();
    if !status.is_success() {
        bail!("{name} API error ({}): {text}", status.as_u16());
    }
    serde_json::from_str(&text).map_err(|e| anyhow!("{name} returned an unparsable body: {e}"))
}

async fn send_openai(
    client: &reqwest::Client,
    model: &ResolvedModel,
    key: &str,
    request: &ImageRequest,
) -> Result<RawImages> {
    let base = model.base_url.trim_end_matches('/');
    let editing = !request.input_images.is_empty();
    let url = format!(
        "{base}/images/{}",
        if editing { "edits" } else { "generations" }
    );
    let mut builder = client
        .post(&url)
        .bearer_auth(key)
        .header(reqwest::header::ACCEPT, "application/json");
    if editing {
        let form = multipart_edit_body(&model.id, request)?;
        builder = builder
            .header(reqwest::header::CONTENT_TYPE, form.content_type())
            .body(form.into_body());
    } else {
        builder = builder.json(&openai_generation_body(&model.id, request));
    }
    let body = post_json(builder, &label(model)).await?;
    parse_openai_response(&body)
}

async fn send_openrouter(
    client: &reqwest::Client,
    model: &ResolvedModel,
    key: &str,
    request: &ImageRequest,
) -> Result<RawImages> {
    let url = format!(
        "{}/images/generations",
        model.base_url.trim_end_matches('/')
    );
    let builder = client
        .post(&url)
        .bearer_auth(key)
        .header(reqwest::header::ACCEPT, "application/json")
        .json(&openrouter_body(&model.id, request));
    let body = post_json(builder, &label(model)).await?;
    parse_openai_response(&body)
}

async fn send_google(
    client: &reqwest::Client,
    model: &ResolvedModel,
    key: &str,
    request: &ImageRequest,
) -> Result<RawImages> {
    let id = model.id.strip_prefix("models/").unwrap_or(&model.id);
    let url = format!(
        "{}/models/{id}:generateContent",
        model.base_url.trim_end_matches('/')
    );
    let builder = client
        .post(&url)
        .header("x-goog-api-key", key)
        .header(reqwest::header::ACCEPT, "application/json")
        .json(&google_body(request));
    let body = post_json(builder, &label(model)).await?;
    parse_google_response(&body)
}

async fn send(
    client: &reqwest::Client,
    model: &ResolvedModel,
    api: ImageApi,
    key: &str,
    request: &ImageRequest,
) -> Result<RawImages> {
    match api {
        ImageApi::OpenAi => send_openai(client, model, key, request).await,
        ImageApi::OpenRouter => send_openrouter(client, model, key, request).await,
        ImageApi::Google => send_google(client, model, key, request).await,
    }
}

/// Resolve one wire image to bytes: inline base64, a `data:` URL, or a fetched `http(s)` URL.
async fn materialize(client: &reqwest::Client, raw: RawImage) -> Result<GeneratedImage> {
    if let Some(inline) = raw.b64 {
        let (payload, inline_mime) = normalize_data_url(&inline);
        let mime_type = raw
            .mime_type
            .or(inline_mime)
            .unwrap_or_else(|| "image/png".to_string());
        return Ok(GeneratedImage {
            data: payload,
            mime_type,
            size: None,
            quality: None,
        });
    }
    let url = raw
        .url
        .ok_or_else(|| anyhow!("image entry has neither data nor url"))?;
    if url.starts_with("data:") {
        let (payload, mime) = normalize_data_url(&url);
        return Ok(GeneratedImage {
            data: payload,
            mime_type: mime.unwrap_or_else(|| "image/png".to_string()),
            size: None,
            quality: None,
        });
    }
    let response = client
        .get(&url)
        .send()
        .await
        .map_err(|e| anyhow!("fetching the generated image failed: {e}"))?;
    let status = response.status();
    if !status.is_success() {
        bail!(
            "fetching the generated image failed: HTTP {}",
            status.as_u16()
        );
    }
    let mime_type = response
        .headers()
        .get(reqwest::header::CONTENT_TYPE)
        .and_then(|value| value.to_str().ok())
        .map(|value| value.split(';').next().unwrap_or(value).trim().to_string())
        .filter(|value| !value.is_empty())
        .unwrap_or_else(|| "image/png".to_string());
    let bytes = response
        .bytes()
        .await
        .map_err(|e| anyhow!("reading the generated image failed: {e}"))?;
    Ok(GeneratedImage {
        data: STANDARD.encode(&bytes),
        mime_type,
        size: None,
        quality: None,
    })
}

