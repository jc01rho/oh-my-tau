/// Which wire format a candidate's api speaks.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ImageApi {
    /// `openai-images`
    OpenAi,
    /// `openrouter-images`
    OpenRouter,
    /// `google-generative-ai`
    Google,
}

/// The transport for an api id, or `None` when the api is not a ported image-generation one.
#[must_use]
pub fn transport_for(api: &str) -> Option<ImageApi> {
    match api {
        "openai-images" => Some(ImageApi::OpenAi),
        "openrouter-images" => Some(ImageApi::OpenRouter),
        "google-generative-ai" => Some(ImageApi::Google),
        _ => None,
    }
}

/// `isImageGenerationApi` restricted to the transports this module implements.
#[must_use]
pub fn is_image_generation_api(api: &str) -> bool {
    transport_for(api).is_some()
}

// ---------------------------------------------------------------- request bodies

/// The `size` to ask a provider for: an explicit `image_size` wins, else the aspect ratio's
/// nearest size, else nothing (provider default).
#[must_use]
pub fn resolved_size(image_size: Option<&str>, aspect_ratio: Option<&str>) -> Option<String> {
    if let Some(size) = image_size.filter(|s| IMAGE_SIZES.contains(s)) {
        return Some(size.to_string());
    }
    aspect_ratio.and_then(aspect_size).map(str::to_string)
}

fn parse_size(size: &str) -> Option<(u32, u32)> {
    let (width, height) = size.split_once('x')?;
    Some((width.trim().parse().ok()?, height.trim().parse().ok()?))
}

/// OpenAI text-to-image body (`/images/generations`).
#[must_use]
pub fn openai_generation_body(model: &str, req: &ImageRequest) -> Value {
    let mut body = json!({
        "model": model,
        "prompt": &req.prompt,
        "n": req.count.max(1),
        "response_format": "b64_json"
    });
    if let Some(size) = resolved_size(req.image_size.as_deref(), req.aspect_ratio.as_deref()) {
        body["size"] = json!(size);
    }
    body
}

/// OpenRouter body (`/images/generations`): `aspect_ratio` is native, references are data URLs.
#[must_use]
pub fn openrouter_body(model: &str, req: &ImageRequest) -> Value {
    let mut body = json!({
        "model": model,
        "prompt": &req.prompt,
        "n": req.count.max(1)
    });
    if let Some(ratio) = req
        .aspect_ratio
        .as_deref()
        .filter(|r| ASPECT_RATIOS.contains(r))
    {
        body["aspect_ratio"] = json!(ratio);
    }
    if let Some(size) = resolved_size(req.image_size.as_deref(), None) {
        body["size"] = json!(size);
    }
    if !req.input_images.is_empty() {
        let references: Vec<Value> = req
            .input_images
            .iter()
            .map(|image| {
                json!({
                    "type": "image_url",
                    "image_url": {"url": format!("data:{};base64,{}", image.mime_type, image.data)}
                })
            })
            .collect();
        body["input_references"] = json!(references);
    }
    body
}

/// Google body (`:generateContent`): prompt text plus inline reference images, `IMAGE` modality,
/// and the aspect ratio under `generationConfig.imageConfig`.
#[must_use]
pub fn google_body(req: &ImageRequest) -> Value {
    let mut parts = vec![json!({"text": &req.prompt})];
    for image in &req.input_images {
        parts.push(json!({
            "inlineData": {"mimeType": image.mime_type, "data": image.data}
        }));
    }
    let mut generation_config = json!({"responseModalities": ["TEXT", "IMAGE"]});
    if let Some(ratio) = req
        .aspect_ratio
        .as_deref()
        .filter(|r| ASPECT_RATIOS.contains(r))
    {
        generation_config["imageConfig"] = json!({"aspectRatio": ratio});
    }
    json!({
        "contents": [{"role": "user", "parts": parts}],
        "generationConfig": generation_config
    })
}

// ---------------------------------------------------------------- multipart

/// Hand-rolled multipart body (the workspace `reqwest` build has no `multipart` feature).
struct Multipart {
    boundary: String,
    body: Vec<u8>,
}

impl Multipart {
    fn new() -> Self {
        Self {
            boundary: format!("----omp-image-{}", unique_id()),
            body: Vec::new(),
        }
    }

    fn content_type(&self) -> String {
        format!("multipart/form-data; boundary={}", self.boundary)
    }

    fn push_field(&mut self, name: &str, value: &str) {
        self.body.extend_from_slice(
            format!(
                "--{}\r\nContent-Disposition: form-data; name=\"{name}\"\r\n\r\n{value}\r\n",
                self.boundary
            )
            .as_bytes(),
        );
    }

    fn push_file(&mut self, name: &str, filename: &str, mime_type: &str, bytes: &[u8]) {
        self.body.extend_from_slice(
            format!(
                "--{}\r\nContent-Disposition: form-data; name=\"{name}\"; filename=\"{filename}\"\r\nContent-Type: {mime_type}\r\n\r\n",
                self.boundary
            )
            .as_bytes(),
        );
        self.body.extend_from_slice(bytes);
        self.body.extend_from_slice(b"\r\n");
    }

    fn into_body(mut self) -> Vec<u8> {
        self.body
            .extend_from_slice(format!("--{}--\r\n", self.boundary).as_bytes());
        self.body
    }
}

/// OpenAI `/images/edits` form: `model`, `prompt`, `n`, optional `size`, then each reference
/// image as `image[]`.
fn multipart_edit_body(model: &str, req: &ImageRequest) -> Result<Multipart> {
    let mut form = Multipart::new();
    form.push_field("model", model);
    form.push_field("prompt", &req.prompt);
    form.push_field("n", &req.count.max(1).to_string());
    if let Some(size) = resolved_size(req.image_size.as_deref(), req.aspect_ratio.as_deref()) {
        form.push_field("size", &size);
    }
    for (index, image) in req.input_images.iter().enumerate() {
        let bytes = STANDARD
            .decode(&image.data)
            .map_err(|e| anyhow!("input image {} is not base64: {e}", index + 1))?;
        let filename = format!("image-{}.{}", index + 1, image_extension(&image.mime_type));
        form.push_file("image[]", &filename, &image.mime_type, &bytes);
    }
    Ok(form)
}

// ---------------------------------------------------------------- response parsing

fn parse_usage(usage: Option<&Value>) -> ImageUsage {
    let count = |key: &str| {
        usage
            .and_then(|u| u.get(key))
            .and_then(Value::as_u64)
            .unwrap_or(0)
    };
    let mut parsed = ImageUsage {
        input_tokens: count("input_tokens"),
        output_tokens: count("output_tokens"),
        total_tokens: count("total_tokens"),
    };
    if parsed.total_tokens == 0 {
        parsed.total_tokens = parsed.input_tokens + parsed.output_tokens;
    }
    parsed
}

fn provider_error(value: &Value) -> Option<String> {
    let error = value.get("error")?;
    Some(
        error
            .get("message")
            .and_then(Value::as_str)
            .or_else(|| error.as_str())
            .unwrap_or("unknown error")
            .to_string(),
    )
}

/// OpenAI / OpenRouter responses: `data[].b64_json` (or `url`), `usage`, `model`.
///
/// # Errors
/// The body carries an `error` object instead of images.
pub fn parse_openai_response(value: &Value) -> Result<RawImages> {
    if let Some(message) = provider_error(value) {
        bail!("provider error: {message}");
    }
    let mut images = Vec::new();
    let mut text = None;
    for entry in value
        .get("data")
        .and_then(Value::as_array)
        .map(Vec::as_slice)
        .unwrap_or_default()
    {
        let b64 = entry
            .get("b64_json")
            .and_then(Value::as_str)
            .map(str::to_string);
        let url = entry.get("url").and_then(Value::as_str).map(str::to_string);
        if b64.is_none() && url.is_none() {
            continue;
        }
        if text.is_none() {
            text = entry
                .get("revised_prompt")
                .and_then(Value::as_str)
                .map(str::to_string);
        }
        images.push(RawImage {
            b64,
            url,
            mime_type: None,
        });
    }
    Ok(RawImages {
        images,
        text,
        usage: parse_usage(value.get("usage")),
        model: value
            .get("model")
            .and_then(Value::as_str)
            .map(str::to_string),
    })
}

/// Google responses: text parts concatenated, `inlineData` / `inline_data` images collected.
///
/// # Errors
/// The body carries an `error` object instead of candidates.
pub fn parse_google_response(value: &Value) -> Result<RawImages> {
    if let Some(message) = provider_error(value) {
        bail!("provider error: {message}");
    }
    let mut images = Vec::new();
    let mut text = String::new();
    let parts = value
        .pointer("/candidates/0/content/parts")
        .and_then(Value::as_array)
        .map(Vec::as_slice)
        .unwrap_or_default();
    for part in parts {
        if let Some(chunk) = part.get("text").and_then(Value::as_str) {
            if !text.is_empty() {
                text.push('\n');
            }
            text.push_str(chunk);
        }
        let inline = part.get("inlineData").or_else(|| part.get("inline_data"));
        if let Some(inline) = inline {
            if let Some(data) = inline.get("data").and_then(Value::as_str) {
                let mime_type = inline
                    .get("mimeType")
                    .or_else(|| inline.get("mime_type"))
                    .and_then(Value::as_str)
                    .map(str::to_string);
                images.push(RawImage {
                    b64: Some(data.to_string()),
                    url: None,
                    mime_type,
                });
            }
        }
    }
    Ok(RawImages {
        images,
        text: (!text.is_empty()).then_some(text),
        usage: ImageUsage::default(),
        model: value
            .get("modelVersion")
            .and_then(Value::as_str)
            .map(str::to_string),
    })
}

