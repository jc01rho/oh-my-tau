/// `normalizeDataUrl`: `data:<mime>;base64,<payload>` splits into payload + mime; anything else
/// comes back untouched.
#[must_use]
pub fn normalize_data_url(data: &str) -> (String, Option<String>) {
    let raw = || (data.to_string(), None);
    let Some(rest) = data.strip_prefix("data:") else {
        return raw();
    };
    let Some((meta, payload)) = rest.split_once(',') else {
        return raw();
    };
    let Some(mime) = meta.strip_suffix(";base64") else {
        return raw();
    };
    if mime.is_empty() || mime.contains(';') || payload.is_empty() {
        return raw();
    }
    (payload.to_string(), Some(mime.to_string()))
}

/// Image mime from magic bytes (`parseImageMetadata`'s mime half).
#[must_use]
pub fn sniff_mime(bytes: &[u8]) -> Option<&'static str> {
    if bytes.starts_with(&[0x89, b'P', b'N', b'G', 0x0d, 0x0a, 0x1a, 0x0a]) {
        return Some("image/png");
    }
    if bytes.starts_with(&[0xff, 0xd8, 0xff]) {
        return Some("image/jpeg");
    }
    if bytes.starts_with(b"GIF8") {
        return Some("image/gif");
    }
    if bytes.len() >= 12 && bytes.starts_with(b"RIFF") && &bytes[8..12] == b"WEBP" {
        return Some("image/webp");
    }
    None
}

/// File extension for a generated image mime (`imageExtension`); unknown types fall back to png.
#[must_use]
pub fn image_extension(mime_type: &str) -> &'static str {
    match mime_type {
        "image/png" => "png",
        "image/jpeg" => "jpg",
        "image/gif" => "gif",
        "image/webp" => "webp",
        _ => "png",
    }
}

fn load_image_from_path(image_path: &str, cwd: &Path) -> Result<InputImage> {
    let resolved = if Path::new(image_path).is_absolute() {
        PathBuf::from(image_path)
    } else {
        cwd.join(image_path)
    };
    let metadata = std::fs::metadata(&resolved).map_err(|e| {
        if e.kind() == std::io::ErrorKind::NotFound {
            anyhow!("Image file not found: {image_path}")
        } else {
            anyhow!("Cannot load '{image_path}': {e}")
        }
    })?;
    if !metadata.is_file() {
        bail!("Cannot load '{image_path}': it is not a regular file.");
    }
    if metadata.len() > MAX_IMAGE_SIZE {
        bail!("Image file too large: {image_path}");
    }
    let bytes =
        std::fs::read(&resolved).with_context(|| format!("reading {}", resolved.display()))?;
    if u64::try_from(bytes.len()).unwrap_or(u64::MAX) > MAX_IMAGE_SIZE {
        bail!("Image file too large: {image_path}");
    }
    let mime_type = sniff_mime(&bytes)
        .ok_or_else(|| anyhow!("Unsupported image type: {image_path}"))?
        .to_string();
    Ok(InputImage {
        data: STANDARD.encode(&bytes),
        mime_type,
    })
}

/// `resolveInputImage`: a path wins over inline data; a data URL carries its own mime.
fn resolve_input_image(input: &ImageInput, cwd: &Path) -> Result<InputImage> {
    if let Some(path) = input.path.as_deref().filter(|p| !p.is_empty()) {
        return load_image_from_path(path, cwd);
    }
    if let Some(data) = input.data.as_deref().filter(|d| !d.is_empty()) {
        let (payload, inline_mime) = normalize_data_url(data.trim());
        let mime_type = inline_mime
            .or_else(|| input.mime_type.clone())
            .ok_or_else(|| anyhow!("mime_type is required when providing raw base64 data."))?;
        if payload.is_empty() {
            bail!("Image data is empty.");
        }
        return Ok(InputImage {
            data: payload,
            mime_type,
        });
    }
    bail!("input entries must include either path or data.")
}

