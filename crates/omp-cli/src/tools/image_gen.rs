    #[test]
    fn requested_size_resamples_and_relabels() {
        let mut png = Vec::new();
        let canvas = image::RgbaImage::from_pixel(2, 1, image::Rgba([255, 0, 0, 255]));
        image::DynamicImage::ImageRgba8(canvas)
            .write_to(&mut Cursor::new(&mut png), image::ImageFormat::Png)
            .unwrap();
        let generated = GeneratedImage {
            data: STANDARD.encode(&png),
            mime_type: "image/png".to_string(),
            size: None,
            quality: None,
        };

        let resized = at_requested_size(&generated, Some("4x4")).unwrap();
        assert_eq!(resized.size.as_deref(), Some("4x4"));
        let decoded = image::load_from_memory(&STANDARD.decode(&resized.data).unwrap()).unwrap();
        assert_eq!((decoded.width(), decoded.height()), (4, 4));

        // already at the requested size: bytes are untouched
        let same = at_requested_size(&generated, Some("2x1")).unwrap();
        assert_eq!(same.data, generated.data);
        assert_eq!(same.size.as_deref(), Some("2x1"));

        // no requested size: pass through
        assert_eq!(
            at_requested_size(&generated, None).unwrap().data,
            generated.data
        );
    }

