/// One reference image, either a path or inline base64.
#[derive(Debug, Clone, Default, Deserialize)]
pub struct ImageInput {
    #[serde(default)]
    pub path: Option<String>,
    #[serde(default)]
    pub data: Option<String>,
    #[serde(default)]
    pub mime_type: Option<String>,
}

/// `generate_image` parameters (`imageGenSchema`).
#[derive(Debug, Clone, Deserialize)]
pub struct ImageGenParams {
    pub subject: String,
    #[serde(default)]
    pub action: Option<String>,
    #[serde(default)]
    pub scene: Option<String>,
    #[serde(default)]
    pub composition: Option<String>,
    #[serde(default)]
    pub lighting: Option<String>,
    #[serde(default)]
    pub style: Option<String>,
    #[serde(default)]
    pub text: Option<String>,
    #[serde(default)]
    pub changes: Option<Vec<String>>,
    #[serde(default)]
    pub aspect_ratio: Option<String>,
    #[serde(default)]
    pub image_size: Option<String>,
    #[serde(default)]
    pub input: Option<Vec<ImageInput>>,
    #[serde(default)]
    pub model: Option<String>,
}

/// Reject values the schema advertises but a hand-written call can still get wrong.
///
/// # Errors
/// Empty subject, an `aspect_ratio` / `image_size` outside the enum, or an `input` entry with
/// neither `path` nor `data`.
pub fn validate(params: &ImageGenParams) -> Result<()> {
    if params.subject.trim().is_empty() {
        bail!("subject must not be empty");
    }
    if let Some(ratio) = params.aspect_ratio.as_deref() {
        if !ASPECT_RATIOS.contains(&ratio) {
            bail!("aspect_ratio must be one of {}", ASPECT_RATIOS.join(", "));
        }
    }
    if let Some(size) = params.image_size.as_deref() {
        if !IMAGE_SIZES.contains(&size) {
            bail!("image_size must be one of {}", IMAGE_SIZES.join(", "));
        }
    }
    for (index, input) in params.input.iter().flatten().enumerate() {
        let has_path = input.path.as_deref().is_some_and(|p| !p.is_empty());
        let has_data = input.data.as_deref().is_some_and(|d| !d.is_empty());
        if !has_path && !has_data {
            bail!("input[{index}] must include either path or data.");
        }
    }
    Ok(())
}

// ---------------------------------------------------------------- prompt

/// `assemblePrompt`: subject clause, then composition / lighting / style sentences, then the
/// optional `Text:` and `Changes:` blocks. Trailing punctuation is stripped per part so the
/// joined sentence ends with exactly one period.
#[must_use]
pub fn assemble_prompt(params: &ImageGenParams) -> String {
    let mut parts: Vec<String> = Vec::new();
    let mut subject_parts = vec![params.subject.clone()];
    for extra in [&params.action, &params.scene] {
        if let Some(value) = extra.as_deref().filter(|v| !v.is_empty()) {
            subject_parts.push(value.to_string());
        }
    }
    parts.push(subject_parts.join(", "));
    for extra in [&params.composition, &params.lighting, &params.style] {
        if let Some(value) = extra.as_deref().filter(|v| !v.is_empty()) {
            parts.push(value.to_string());
        }
    }
    let stripped: Vec<String> = parts
        .iter()
        .map(|part| part.trim_end_matches(['.', '!', ',', ';', ':']).to_string())
        .collect();
    let mut result = format!("{}.", stripped.join(". "));
    if let Some(text) = params.text.as_deref().filter(|t| !t.is_empty()) {
        result.push_str(&format!("\n\nText: {text}"));
    }
    if let Some(changes) = params.changes.as_ref().filter(|c| !c.is_empty()) {
        let lines: Vec<String> = changes.iter().map(|change| format!("- {change}")).collect();
        result.push_str(&format!("\n\nChanges:\n{}", lines.join("\n")));
    }
    result
}

