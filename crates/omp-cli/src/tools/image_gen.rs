static COUNTER: AtomicU64 = AtomicU64::new(0);

/// Process-unique suffix for temp filenames (omp uses a snowflake; nanos + counter is enough).
fn unique_id() -> String {
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |d| d.as_nanos());
    let sequence = COUNTER.fetch_add(1, Ordering::Relaxed) & 0xffff;
    format!("{nanos:x}{sequence:04x}")
}

/// `atRequestedSize`: providers treat `image_size` as a hint, so a different native size is
/// resampled to exactly what was asked for (JPEG stays JPEG at quality 92, everything else PNG).
///
/// # Errors
/// The payload is not base64, is not a decodable image, or cannot be re-encoded.
pub fn at_requested_size(
    image: &GeneratedImage,
    requested: Option<&str>,
) -> Result<GeneratedImage> {
    let Some(requested) = requested else {
        return Ok(image.clone());
    };
    let Some((width, height)) = parse_size(requested) else {
        return Ok(image.clone());
    };
    let bytes = STANDARD
        .decode(&image.data)
        .map_err(|e| anyhow!("generated image is not base64: {e}"))?;
    let decoded = image::load_from_memory(&bytes)
        .map_err(|e| anyhow!("generated image cannot be decoded: {e}"))?;
    if decoded.width() == width && decoded.height() == height {
        let mut same = image.clone();
        same.size = Some(requested.to_string());
        return Ok(same);
    }
    let resized = decoded.resize_exact(width, height, image::imageops::FilterType::Lanczos3);
    let jpeg = image.mime_type == "image/jpeg";
    let mut encoded = Vec::new();
    if jpeg {
        let mut cursor = Cursor::new(&mut encoded);
        image::codecs::jpeg::JpegEncoder::new_with_quality(&mut cursor, 92)
            .encode_image(&resized)
            .map_err(|e| anyhow!("re-encoding the generated image failed: {e}"))?;
    } else {
        resized
            .write_to(&mut Cursor::new(&mut encoded), image::ImageFormat::Png)
            .map_err(|e| anyhow!("re-encoding the generated image failed: {e}"))?;
    }
    Ok(GeneratedImage {
        data: STANDARD.encode(&encoded),
        mime_type: if jpeg { "image/jpeg" } else { "image/png" }.to_string(),
        size: Some(requested.to_string()),
        quality: image.quality.clone(),
    })
}

/// Write every image to `<tmpdir>/omp-image-<id>.<ext>` and return the paths.
///
/// # Errors
/// A payload is not base64, or a temp file cannot be written.
pub fn save_images_to_temp(images: &[GeneratedImage]) -> Result<Vec<PathBuf>> {
    let directory = std::env::temp_dir();
    let mut paths = Vec::with_capacity(images.len());
    for image in images {
        let path = directory.join(format!(
            "omp-image-{}.{}",
            unique_id(),
            image_extension(&image.mime_type)
        ));
        let bytes = STANDARD
            .decode(&image.data)
            .map_err(|e| anyhow!("generated image is not base64: {e}"))?;
        std::fs::write(&path, bytes).with_context(|| format!("writing {}", path.display()))?;
        paths.push(path);
    }
    Ok(paths)
}

/// The LLM-facing tool text: provider, the model that actually ran, then one line per file.
#[must_use]
pub fn render_result_text(
    provider: &str,
    catalog_model: &str,
    ran_model: &str,
    images: &[GeneratedImage],
    paths: &[PathBuf],
    text: Option<&str>,
) -> String {
    let mut lines = vec![format!("Provider: {provider}")];
    if ran_model == catalog_model {
        lines.push(format!("Model: {ran_model}"));
    } else {
        lines.push(format!(
            "Model: {ran_model} (catalog entry {provider}/{catalog_model})"
        ));
    }
    lines.push(format!("Generated {} image(s):", paths.len()));
    for (index, path) in paths.iter().enumerate() {
        let metadata: Vec<String> = images.get(index).map_or_else(Vec::new, |image| {
            let mut parts = Vec::new();
            if let Some(size) = &image.size {
                parts.push(size.clone());
            }
            if let Some(quality) = &image.quality {
                parts.push(format!("quality {quality}"));
            }
            parts
        });
        if metadata.is_empty() {
            lines.push(format!("  {}", path.display()));
        } else {
            lines.push(format!("  {} ({})", path.display(), metadata.join(", ")));
        }
    }
    if let Some(trailing) = text.map(str::trim).filter(|t| !t.is_empty()) {
        lines.push(String::new());
        lines.push(trailing.to_string());
    }
    lines.join("\n")
}

/// One failure reason flattened onto a single line and capped, without a trailing period (the
/// aggregate message supplies it).
fn truncate_failure(reason: &str) -> String {
    let collapsed = reason.split_whitespace().collect::<Vec<_>>().join(" ");
    let trimmed = collapsed.trim();
    let capped: String = trimmed.chars().take(MAX_FAILURE_REASON_CHARS).collect();
    let flattened = capped.trim_end_matches('.').to_string();
    if trimmed.chars().count() > MAX_FAILURE_REASON_CHARS {
        format!("{flattened}...")
    } else {
        flattened
    }
}

/// The `AggregateError` text: attempted chain, per-provider reasons, and everything skipped.
#[must_use]
pub fn exhausted_message(candidates: &[String], failures: &[String], skipped: &[String]) -> String {
    let attempted = candidates.join(", ");
    let mut message = String::from("Image generation exhausted the resolved image chain");
    if !attempted.is_empty() {
        message.push_str(": ");
        message.push_str(&attempted);
    }
    message.push('.');
    if !failures.is_empty() {
        let reasons: Vec<String> = failures
            .iter()
            .map(|reason| truncate_failure(reason))
            .collect();
        message.push_str(" Failures: ");
        message.push_str(&reasons.join("; "));
        message.push('.');
    }
    if !skipped.is_empty() {
        message.push_str(" Skipped: ");
        message.push_str(&skipped.join(", "));
        message.push('.');
    }
    message
}

// ---------------------------------------------------------------- candidates

fn dedupe(selectors: Vec<String>) -> Vec<String> {
    let mut seen = HashSet::new();
    selectors
        .into_iter()
        .filter(|selector| seen.insert(selector.clone()))
        .collect()
}

/// `defaultImageCandidates` order: the role's own selector, then the session's image model, then
/// `retry.fallbackChains.image`. An explicit `model` selector replaces the whole chain.
#[must_use]
pub fn candidate_selectors(
    explicit: Option<&str>,
    session_image_model: Option<&str>,
    role_selector: &str,
    fallbacks: &[String],
) -> Vec<String> {
    if let Some(selector) = explicit.map(str::trim).filter(|s| !s.is_empty()) {
        return vec![selector.to_string()];
    }
    let mut ordered = vec![role_selector.to_string()];
    if let Some(session) = session_image_model.map(str::trim).filter(|s| !s.is_empty()) {
        ordered.push(session.to_string());
    }
    ordered.extend(
        fallbacks
            .iter()
            .filter(|fallback| !fallback.trim().is_empty())
            .cloned(),
    );
    dedupe(ordered)
}

/// Everything the tool needs from the session that is not in the parameters.
#[derive(Debug, Clone)]
pub struct ImageGenContext {
    pub dir: AgentDir,
    pub cwd: PathBuf,
    /// `cfgOffline`: only the active provider may be used.
    pub offline: bool,
    pub active_provider: Option<String>,
    /// The session model, when it is itself an image-generation model (stands in for omp's
    /// `sessionModel.imageModel` / `hostedImage` legs).
    pub session_model: Option<String>,
}

/// A successful generation.
#[derive(Debug, Clone, Serialize)]
pub struct ImageGenOutcome {
    pub provider: String,
    pub model: String,
    pub image_count: usize,
    pub image_paths: Vec<PathBuf>,
    pub images: Vec<GeneratedImage>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub response_text: Option<String>,
    pub usage: ImageUsage,
    /// The LLM-facing content.
    pub text: String,
}

fn resolve_candidates(
    params: &ImageGenParams,
    ctx: &ImageGenContext,
) -> Result<Vec<ResolvedModel>> {
    if let Some(explicit) = params
        .model
        .as_deref()
        .map(str::trim)
        .filter(|s| !s.is_empty())
    {
        let model = omp_providers::resolve_in(&ctx.dir, explicit)
            .ok()
            .ok_or_else(|| {
                anyhow!("Image model selector did not match an available image model: {explicit}")
            })?;
        return Ok(vec![model]);
    }
    let primary = omp_providers::resolve_in(&ctx.dir, "image")
        .map_err(|e| anyhow!("no image model role configured: {e}"))?;
    let ordered = candidate_selectors(
        None,
        ctx.session_model.as_deref(),
        &primary.selector,
        &primary.fallbacks,
    );
    let mut candidates: Vec<ResolvedModel> = Vec::new();
    for (index, selector) in ordered.iter().enumerate() {
        let resolved = if index == 0 && selector == &primary.selector {
            Ok(primary.clone())
        } else {
            omp_providers::resolve_in(&ctx.dir, selector)
        };
        match resolved {
            Ok(model) => candidates.push(model),
            Err(error) => {
                tracing::debug!(selector = %selector, %error, "image candidate did not resolve");
            }
        }
    }
    if candidates.is_empty() {
        candidates.push(primary);
    }
    let mut seen = HashSet::new();
    candidates.retain(|model| seen.insert((model.provider.clone(), model.id.clone())));
    Ok(candidates)
}

// ---------------------------------------------------------------- execute

/// Run one `generate_image` request, trying each resolved candidate in order.
///
/// # Errors
/// Invalid parameters, no resolvable candidate, unreadable input images, or every candidate
/// failing (see [`exhausted_message`]). A candidate that answers without any image is a hard
/// error, as upstream.
pub async fn execute(params: &ImageGenParams, ctx: &ImageGenContext) -> Result<ImageGenOutcome> {
    validate(params)?;
    let candidates = resolve_candidates(params, ctx)?;
    let prompt = assemble_prompt(params);
    let client = reqwest::Client::builder()
        .timeout(IMAGE_TIMEOUT)
        .build()
        .map_err(|e| anyhow!("building the image HTTP client failed: {e}"))?;
    let attempted: Vec<String> = candidates.iter().map(label).collect();
    let mut failures: Vec<String> = Vec::new();
    let mut skipped: Vec<String> = Vec::new();
    let mut input_images: Option<Vec<InputImage>> = None;

    for model in &candidates {
        let name = label(model);
        if ctx.offline && ctx.active_provider.as_deref() != Some(model.provider.as_str()) {
            skipped.push(format!("{name} (offline provider restriction)"));
            continue;
        }
        let Some(api) = transport_for(&model.api) else {
            skipped.push(format!("{name} (unsupported {})", model.api));
            continue;
        };
        let Some(key) = model.api_key.as_deref().filter(|key| !key.is_empty()) else {
            skipped.push(format!("{name} (credentials unavailable)"));
            continue;
        };
        if input_images.is_none() {
            let mut loaded = Vec::new();
            for input in params.input.iter().flatten() {
                loaded.push(resolve_input_image(input, &ctx.cwd)?);
            }
            input_images = Some(loaded);
        }
        let request = ImageRequest {
            prompt: prompt.clone(),
            input_images: input_images.clone().unwrap_or_default(),
            aspect_ratio: params.aspect_ratio.clone(),
            image_size: params.image_size.clone(),
            count: 1,
        };
        let raw = match send(&client, model, api, key, &request).await {
            Ok(raw) => raw,
            Err(error) => {
                failures.push(error.to_string());
                continue;
            }
        };
        let ran_model = raw.model.clone().unwrap_or_else(|| model.id.clone());
        if raw.images.is_empty() {
            let detail = raw
                .text
                .as_deref()
                .map(|text| format!("\n\n{}", text.trim()))
                .unwrap_or_default();
            bail!("{}/{ran_model} returned no image.{detail}", model.provider);
        }
        let mut images = Vec::with_capacity(raw.images.len());
        for pending in raw.images {
            images.push(materialize(&client, pending).await?);
        }
        let mut resized = Vec::with_capacity(images.len());
        for image in &images {
            resized.push(at_requested_size(image, params.image_size.as_deref())?);
        }
        let image_paths = save_images_to_temp(&resized)?;
        let text = render_result_text(
            &model.provider,
            &model.id,
            &ran_model,
            &resized,
            &image_paths,
            raw.text.as_deref(),
        );
        return Ok(ImageGenOutcome {
            provider: model.provider.clone(),
            model: ran_model,
            image_count: resized.len(),
            image_paths,
            images: resized,
            response_text: raw.text,
            usage: raw.usage,
            text,
        });
    }

    Err(anyhow!(exhausted_message(&attempted, &failures, &skipped)))
}

